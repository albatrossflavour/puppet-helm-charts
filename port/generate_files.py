#!/usr/bin/env python3
"""Generate a chart's config files from the module templates they are ported from.

usage: generate_files.py <cd4pe|scm> [--check]

The input is the rendered-template snapshot in port/snapshots for the module
release named in the chart's ported-from annotation. Each recipe below takes
one rendered template and applies the edits that make it fit Kubernetes. Every
edit has to match something: if a new module release changes a template so an
edit no longer applies, this stops and says which one, because the recipe then
needs a person.

--check writes nothing and fails if a file on disk differs from what would be
generated, which is how CI notices a hand edit or a stale file.
"""
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = {"cd4pe": "cd4peadm", "scm": "complyadm"}


class RecipeError(Exception):
    pass


def sub(text, pattern, replacement, what, flags=re.M):
    """Replace every match of pattern. It is an error for nothing to match."""
    result, count = re.subn(pattern, replacement, text, flags=flags)
    if count == 0:
        raise RecipeError(f"nothing matched for: {what}")
    return result


def cut(text, start, end, what):
    """Remove from the line containing start up to, not including, the line containing end."""
    first = text.find(start)
    last = text.find(end, first + 1) if first >= 0 else -1
    if first < 0 or last < 0:
        raise RecipeError(f"markers not found for: {what}")
    first = text.rfind("\n", 0, first) + 1
    last = text.rfind("\n", 0, last) + 1
    return text[:first] + text[last:]


def tidy(text):
    """Strip trailing spaces and collapse runs of blank lines left behind by the edits."""
    text = re.sub(r"[ \t]+$", "", text, flags=re.M)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip("\n") + "\n"


def header(source, changes, extra=()):
    lines = [f"# Generated by port/generate_files.py from {source}. Do not edit."]
    if changes:
        lines.append("# Changed from the module's version:")
        lines += [f"#   - {change}" for change in changes]
    lines += [f"# {line}" for line in extra]
    return "\n".join(lines) + "\n"


# --- cd4pe -----------------------------------------------------------------

def cd4pe_nginx(text):
    text = cut(text, "# Webhooks", "# Server config", "the webhook server block")
    text = sub(text, r"^(\s*listen\s+\S+:3000) ssl;", r"\1;", "ssl on the :3000 listeners")
    text = sub(text, r"^\s*http2 on;\n", "", "http2")
    text = sub(text, r"^\s*ssl_\w+ .*\n", "", "the ssl_ directives")
    text = sub(text, r"^.*Strict-Transport-Security.*\n", "", "the HSTS header")
    text = sub(text, r"access_log /app/logs/access\.log;", "access_log /dev/stdout;", "the access log path")
    text = sub(text, r"error_log /app/logs/error\.log;", "error_log /dev/stderr;", "the error log path")
    return header(
        "cd4peadm templates/nginx/base.conf.template.epp",
        [
            "TLS removed from :3000, the ingress controller terminates it",
            "webhook server block removed, the backend ingress goes straight to pipelinesinfra:8000",
            "logs go to stdout and stderr instead of /app/logs",
        ],
        ["CD4PE_SERVICE and QUERY_SERVICE are filled in by the image's envsubst step at start."],
    ) + tidy(text)


def cd4pe_log4j(text):
    text = sub(text, r"^(appender\.\w+\.type) = RollingFile$", r"\1 = Console", "the appender types")
    text = sub(text, r"^appender\.\w+\.(fileName|filePattern|policies\S*|strategy\S*) = .*\n", "", "the file and rollover settings")
    # Both appenders now share one stream, so mark the access lines.
    text = sub(text, r"^(appender\.access\.layout\.pattern) = %m%n$", r"\1 = access: %m%n", "the access log pattern")
    return header(
        "cd4peadm templates/log4j2.properties.epp",
        ["both appenders write to the console instead of rolling files in /app/logs"],
    ) + tidy(text)


def cd4pe_postgresql_conf(text):
    text = sub(text, r"^logging_collector\s*=\s*on.*$", "logging_collector = off", "the logging collector")
    text = sub(text, r"^log_(directory|filename)\s*=.*\n", "", "the log file settings")
    return header(
        "cd4peadm templates/postgres/postgresql.conf.epp",
        ["the logging collector is off, so logs go to stderr for kubectl logs"],
    ) + tidy(text)


def pg_hba(module):
    def recipe(text):
        return header(f"{module} files/postgres/pg_hba.conf", []) + tidy(text)
    return recipe


# --- scm -------------------------------------------------------------------

def scm_frontdoor(text):
    text = sub(text, r"^\s*# set the name server based on.*\n\s*resolver .*\n", "", "the docker resolver")
    text = sub(
        text,
        r"^\s*server \{\n\s*server_name _;\n\s*listen 8080 default_server[^\n]*\n\s*return 301 [^\n]*\n\s*\}\n",
        "",
        "the HTTP to HTTPS redirect server",
    )
    text = sub(text, r"listen 8443 default_server reuseport backlog=511 ssl;", "listen 8080 default_server reuseport backlog=511;", "the TLS listener")
    text = sub(text, r"^\s*# configure TLS certificate file locations\n(\s*ssl_certificate\w* .*\n)+", "", "the certificate paths")
    text = sub(text, r"^\s*# enforce ssl on server side\n\s*if \(\$scheme = http\) \{\n.*\n\s*\}\n", "", "the scheme redirect")
    text = sub(text, r"^\s*# turn on session caching.*?^\s*ssl_ecdh_curve [^\n]*\n", "", "the TLS session and cipher settings", flags=re.M | re.S)
    for name, port in (("gatekeeper", 3001), ("identity", 8080), ("scarpy", 8088)):
        text = sub(
            text,
            rf"set \${name} http://comply_{name}:{port};\s*\n\s*proxy_pass \${name};",
            f"proxy_pass http://@@FULLNAME@@-{name}:{port};",
            f"the {name} upstream",
        )
    text = sub(text, r"X-Forwarded-Proto \$scheme;", "X-Forwarded-Proto https;", "X-Forwarded-Proto")
    text = sub(text, r"(proxy_set_header X-Scheme\s+)\$scheme;", r"\1https;", "X-Scheme")
    text = sub(
        text,
        r"(^\s*location \^~ /auth/admin \{\n).*?(^\s*\}\n)",
        r"\1@@ADMIN_BLOCK@@\n\2",
        "the Keycloak admin location",
        flags=re.M | re.S,
    )
    if "comply_" in text or re.search(r"\bssl", text):
        raise RecipeError("a docker service name or an ssl setting is left in the frontdoor config")
    return header(
        "complyadm templates/frontdoor/nginx_conf.epp",
        [
            "TLS and the 8080 to 8443 redirect removed, the ingress controller terminates TLS",
            "the one server block listens on plain 8080",
            "upstreams are Service names, resolved at start, so no docker resolver",
            "X-Forwarded-Proto is fixed at https, since the ingress is the only way in",
        ],
        ["The chart replaces the FULLNAME placeholder, and switches the /auth/admin block on frontdoor.keycloakAdminConsole."],
    ) + tidy(text)


def scm_mtls_proxy(text):
    text = sub(text, r"^\s*resolver .*\n", "", "the docker resolver")
    text = sub(text, r"^\s*set \$comply_ui http://comply_ui:3001;\n", "", "the ui variable")
    text = sub(text, r"^\s*set \$comply_scarpy http://comply_scarpy:8088;\n", "", "the scarpy variable")
    text = sub(text, r"\$comply_scarpy/", "http://comply_scarpy/", "the scarpy proxy targets")
    text = sub(text, r"\$comply_ui/", "http://comply_ui/", "the ui proxy targets")
    upstreams = (
        "  upstream comply_scarpy {\n    server @@FULLNAME@@-scarpy:8088;\n  }\n\n"
        "  upstream comply_ui {\n    server @@FULLNAME@@-ui:3001;\n  }\n\n"
    )
    text = sub(text, r"^(\s*server \{\n\s*listen 8081;)", lambda m: upstreams + m.group(1), "the place for the upstream blocks")
    text = sub(text, r"^error_log /dev/stderr debug;", "error_log /dev/stderr notice;", "the error log level")
    return header(
        "complyadm templates/mtls_proxy/nginx_conf.epp",
        [
            "upstreams are Service names in upstream blocks, so no docker resolver",
            "the error log is at notice, not debug",
        ],
        ["The chart replaces the FULLNAME placeholder."],
    ) + tidy(text)


def scm_oauth2_proxy(text):
    text = sub(text, r'^client_secret\s*=.*\n', "", "client_secret")
    text = sub(text, r'^cookie_secret\s*=.*\n', "", "cookie_secret")
    return header(
        "complyadm templates/gatekeeper/oauth2_proxy.cfg.epp",
        [
            "client_secret and cookie_secret are left out: they come from OAUTH2_PROXY_CLIENT_SECRET and OAUTH2_PROXY_COOKIE_SECRET",
            "the upstreams are Service names",
        ],
        ["The chart replaces the FULLNAME and HOSTNAME placeholders."],
    ) + tidy(text)


def scm_postgresql_conf(text):
    return header("complyadm templates/postgres/postgresql.conf.epp", []) + tidy(text)


def scm_realm(text):
    # JSON cannot carry a comment. NOTICE says where this file comes from.
    if "<%" in text or "@@CLIENT_SECRET@@" not in text:
        raise RecipeError("the realm did not render with its placeholders")
    return text.strip("\n") + "\n"


RECIPES = {
    "cd4pe": {
        "base.conf.template": ("templates/nginx/base.conf.template.epp", cd4pe_nginx),
        "log4j2.properties": ("templates/log4j2.properties.epp", cd4pe_log4j),
        "postgresql.conf": ("templates/postgres/postgresql.conf.epp", cd4pe_postgresql_conf),
        "pg_hba.conf": ("files/postgres/pg_hba.conf", pg_hba("cd4peadm")),
    },
    "scm": {
        "frontdoor-nginx.conf.tmpl": ("templates/frontdoor/nginx_conf.epp", scm_frontdoor),
        "mtls-proxy-nginx.conf.tmpl": ("templates/mtls_proxy/nginx_conf.epp", scm_mtls_proxy),
        "oauth2_proxy.cfg.tmpl": ("templates/gatekeeper/oauth2_proxy.cfg.epp", scm_oauth2_proxy),
        "postgresql.conf": ("templates/postgres/postgresql.conf.epp", scm_postgresql_conf),
        "pg_hba.conf": ("files/postgres/pg_hba.conf", pg_hba("complyadm")),
        "Puppet-realm.json.tmpl": ("templates/identity/puppet-realm.json.epp", scm_realm),
    },
}


def ported_from(chart):
    module = MODULES[chart]
    text = open(os.path.join(REPO, "charts", chart, "Chart.yaml")).read()
    match = re.search(rf"^\s*puppet-helm-charts/ported-from:\s*{module}\s+(\S+)", text, re.M)
    if not match:
        sys.exit(f"no ported-from annotation for {module} in charts/{chart}/Chart.yaml")
    return module, match.group(1)


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in RECIPES:
        sys.exit(__doc__)
    chart, check = sys.argv[1], "--check" in sys.argv[2:]
    module, version = ported_from(chart)
    snapshot = os.path.join(REPO, "port", "snapshots", f"{module}-{version}.rendered.json")
    if not os.path.exists(snapshot):
        sys.exit(f"no rendered snapshot for {module} {version}: run port/snapshot.sh")
    rendered = json.load(open(snapshot))

    stale = []
    for name, (source, recipe) in RECIPES[chart].items():
        if source not in rendered:
            sys.exit(f"{source} is not in {os.path.basename(snapshot)}: add it to port/render/{module}.yaml")
        try:
            text = recipe(rendered[source])
        except RecipeError as error:
            sys.exit(f"charts/{chart}/files/{name}: the recipe no longer fits {module} {version}: {error}")
        path = os.path.join(REPO, "charts", chart, "files", name)
        current = open(path).read() if os.path.exists(path) else None
        if current == text:
            continue
        stale.append(name)
        if not check:
            with open(path, "w") as out:
                out.write(text)

    extra = sorted(set(os.listdir(os.path.join(REPO, "charts", chart, "files"))) - set(RECIPES[chart]))
    if extra:
        sys.exit(f"charts/{chart}/files has files no recipe produces: {', '.join(extra)}")

    if check and stale:
        sys.exit(f"charts/{chart}/files is out of date for {module} {version}: {', '.join(stale)}. Run port/generate_files.py {chart}")
    print(f"{chart}: {'checked' if check else 'generated'} {len(RECIPES[chart])} files from {module} {version}"
          + (f", {len(stale)} changed: {', '.join(stale)}" if stale and not check else ""))


if __name__ == "__main__":
    main()
